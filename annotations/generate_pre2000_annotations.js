const oldCoins = COINS.filter(coin => Number(coin.year) < 2000);
const existingIds = new Set(
  fs.readdirSync(__dirname)
    .filter(name => name.endsWith('.json'))
    .map(name => path.basename(name, '.json'))
);

let generatedCount = 0;
for (const coin of oldCoins) {
  if (existingIds.has(coin.id) && !FORCE) continue;
  const faces = specs[coin.id];
  if (!faces) throw new Error(`缺少标注规格：${coin.id} ${coin.name}`);

  for (const [face, faceSpec] of Object.entries(faces)) {
    const description = face === 'f' ? coin.description : coin.description2;
    for (const item of faceSpec) {
      if (!description.includes(item.quote)) {
        throw new Error(`${coin.id}_${face} 描述中找不到标记词：${item.quote}`);
      }
    }
  }

  const output = {
    id: coin.id,
    version: 1,
    faces: Object.fromEntries(
      Object.entries(faces).map(([face, items]) => [
        face,
        { image: `coins/img/${coin.id}_${face}.webp`, items }
      ])
    )
  };
  fs.writeFileSync(path.join(__dirname, `${coin.id}.json`), `${JSON.stringify(output, null, 2)}\n`);
  generatedCount++;
}

const finalIds = new Set(
  fs.readdirSync(__dirname)
    .filter(name => name.endsWith('.json'))
    .map(name => path.basename(name, '.json'))
);
const missing = oldCoins.filter(coin => !finalIds.has(coin.id));
if (missing.length) throw new Error(`生成后仍缺少：${missing.map(coin => coin.id).join(', ')}`);

const inRange = value => Number.isFinite(value) && value >= 0 && value <= 1;
for (const coin of oldCoins) {
  const file = path.join(__dirname, `${coin.id}.json`);
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const face of ['f', 'b']) {
    const faceData = data.faces[face];
    if (!faceData || !Array.isArray(faceData.items) || !faceData.items.length) {
      throw new Error(`${coin.id}_${face} 没有标注项`);
    }
    const description = face === 'f' ? BY_ID.get(coin.id).description : BY_ID.get(coin.id).description2;
    const imageFile = path.join(ROOT, faceData.image);
    if (!fs.existsSync(imageFile)) throw new Error(`${coin.id}_${face} 图片不存在：${faceData.image}`);
    for (const item of faceData.items) {
      if (!description.includes(item.quote)) {
        throw new Error(`${coin.id}_${face} 描述中找不到标记词：${item.quote}`);
      }
      for (const region of item.regions) {
        if (region.type === 'rect') {
          if (![region.x, region.y, region.width, region.height].every(inRange) || region.x + region.width > 1 || region.y + region.height > 1) {
            throw new Error(`${coin.id}_${face} 矩形越界：${item.quote}`);
          }
        } else if (region.type === 'ellipse') {
          if (![region.cx, region.cy, region.rx, region.ry].every(inRange) || region.cx - region.rx < 0 || region.cy - region.ry < 0 || region.cx + region.rx > 1 || region.cy + region.ry > 1) {
            throw new Error(`${coin.id}_${face} 椭圆越界：${item.quote}`);
          }
        } else if (region.type === 'polygon') {
          if (!region.points.every(point => point.length === 2 && point.every(inRange))) {
            throw new Error(`${coin.id}_${face} 多边形越界：${item.quote}`);
          }
        } else {
          throw new Error(`${coin.id}_${face} 未知区域类型：${region.type}`);
        }
      }
    }
  }
}

